#!/usr/bin/env bash
#
# One-time setup of a FRESH Ubuntu 22.04/24.04 server (AWS EC2) for the CRM.
# Nothing from any previous server is reused: a new empty PostgreSQL
# database, a freshly generated server/.env with new random secrets, nginx
# for your domain, and the systemd units the auto-deploy pipeline expects.
#
#   sudo DOMAIN=crm.example.com \
#        REPO_URL=git@github.com:<you>/<repo>.git \
#        DEPLOY_BUCKET=<your-deploy-bucket> \
#        bash setup-server.sh
#
# Before running: the instance has the ZenkaraEC2Deploy IAM role attached and,
# for a private repo, root has a read-only deploy key (see deploy/README.md,
# "Fresh server"). Safe to re-run — it never overwrites an existing
# server/.env, database password or nginx certificate.
set -euo pipefail

DOMAIN="${DOMAIN:?set DOMAIN, e.g. crm.example.com}"
REPO_URL="${REPO_URL:?set REPO_URL, e.g. git@github.com:you/repo.git}"
DEPLOY_BUCKET="${DEPLOY_BUCKET:-zenkara-deploy}"
APP=/opt/zenkara-crm
ENV_FILE="$APP/server/.env"
DB_NAME=zenkara_crm
DB_USER=zenkara_crm
RUN_USER=zenkara

log() { echo; echo "── $*"; }
[ "$(id -u)" = 0 ] || { echo "Run as root (sudo)." >&2; exit 1; }

# ── Packages ────────────────────────────────────────────────────────────
log "Installing packages"
apt-get update -y
apt-get install -y ca-certificates curl git gnupg nginx postgresql openssl unzip
if ! command -v node >/dev/null || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 20 ]; then
  curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
  apt-get install -y nodejs
fi
if ! command -v aws >/dev/null; then
  # Ubuntu 24.04 dropped the awscli apt package; AWS's own installer works on both.
  tmp=$(mktemp -d)
  curl -fsSL "https://awscli.amazonaws.com/awscli-exe-linux-$(uname -m).zip" -o "$tmp/awscli.zip"
  unzip -q "$tmp/awscli.zip" -d "$tmp"
  "$tmp/aws/install"
  rm -rf "$tmp"
fi

# ── Service user (the API never runs as root) ───────────────────────────
id "$RUN_USER" >/dev/null 2>&1 || useradd --system --home "$APP" --shell /usr/sbin/nologin "$RUN_USER"

# ── Code ────────────────────────────────────────────────────────────────
log "Cloning $REPO_URL"
if [ ! -d "$APP/.git" ]; then
  # Pin GitHub's host key up front so an SSH clone doesn't stop at a prompt.
  case "$REPO_URL" in git@github.com:*)
    mkdir -p /root/.ssh && chmod 700 /root/.ssh
    grep -q "^github.com " /root/.ssh/known_hosts 2>/dev/null || ssh-keyscan -t ed25519 github.com >> /root/.ssh/known_hosts
  esac
  git clone "$REPO_URL" "$APP"
else
  echo "$APP already cloned — leaving it"
fi

# ── Database (local only — PostgreSQL listens on localhost by default) ──
log "Creating PostgreSQL database $DB_NAME"
if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1; then
  echo "Role $DB_USER exists — keeping its password (it is already in $ENV_FILE)"
  DB_PASS=""
else
  DB_PASS=$(openssl rand -hex 24)   # hex: safe inside DATABASE_URL unescaped
  sudo -u postgres psql -v ON_ERROR_STOP=1 -c "CREATE ROLE $DB_USER LOGIN PASSWORD '$DB_PASS'"
fi
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1 \
  || sudo -u postgres createdb -O "$DB_USER" "$DB_NAME"

# ── server/.env with brand-new secrets ──────────────────────────────────
# Values are double-quoted so both dotenv and systemd's EnvironmentFile read
# them identically (e.g. the space in SMTP_FROM). Root-only: the API gets it
# through EnvironmentFile, which systemd reads as root.
log "Writing $ENV_FILE"
if [ -f "$ENV_FILE" ]; then
  echo "$ENV_FILE already exists — not touching it"
else
  [ -n "$DB_PASS" ] || { echo "DB role exists but $ENV_FILE is missing — reset the role password: sudo -u postgres psql -c \"ALTER ROLE $DB_USER PASSWORD '<new>'\" and write DATABASE_URL by hand." >&2; exit 1; }
  r() { openssl rand -hex 64; }
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/setup-server.sh on $(date -I). Root-only (chmod 600).
NODE_ENV="production"
PORT="4000"
DATABASE_URL="postgresql://$DB_USER:$DB_PASS@127.0.0.1:5432/$DB_NAME"

JWT_SECRET="$(r)"
JWT_EXPIRES_IN="15m"
ENCRYPTION_KEY="$(r)"
QUOTE_SHARE_SECRET="$(r)"
WORKFLOW_WEBHOOK_SECRET="$(r)"

APP_URL="https://$DOMAIN"
FRONTEND_URL="https://$DOMAIN"
CORS_ORIGIN="https://$DOMAIN"

# ── Email (Gmail) — SMTP_PASS is a 16-char Google App Password ──
SMTP_HOST="smtp.gmail.com"
SMTP_PORT="587"
SMTP_USER="zenkaratech@gmail.com"
SMTP_PASS=""
SMTP_FROM="Zenkara 360 <zenkaratech@gmail.com>"
# Platform super admin — receives Approve/Reject links for new company signups
ADMIN_NOTIFY_EMAIL="zenkara360superadmin@gmail.com"

# ── Google OAuth (Sign-In, Drive, Calendar) ──
GOOGLE_CLIENT_ID=""
GOOGLE_CLIENT_SECRET=""

# ── AI (Groq first, OpenAI fallback) ──
GROQ_API_KEY=""
OPENAI_API_KEY=""

# ── Hosted attachment storage (S3 / R2) ──
S3_BUCKET=""
S3_ACCESS_KEY_ID=""
S3_SECRET_ACCESS_KEY=""
S3_REGION=""
S3_ENDPOINT=""

# ── Billing (Stripe) ──
STRIPE_SECRET_KEY=""
STRIPE_WEBHOOK_SECRET=""
STRIPE_PRO_PRICE_ID=""
STRIPE_ENTERPRISE_PRICE_ID=""

# ── WhatsApp (Twilio) ──
TWILIO_ACCOUNT_SID=""
TWILIO_AUTH_TOKEN=""
TWILIO_FROM_NUMBER=""

# ── Web push — generate with: npx web-push generate-vapid-keys ──
VAPID_PUBLIC_KEY=""
VAPID_PRIVATE_KEY=""
VAPID_SUBJECT="mailto:zenkaratech@gmail.com"

# ── Endpoints that stay DISABLED (404) while empty — set only if needed ──
# DEMO_RESET_SECRET: nightly demo re-seed (reset-demo.yml). Not for a live site.
# DIRECTORY_SYNC_SECRET: Entra ID scheduled sync (directory-sync.yml).
# PLATFORM_BOOTSTRAP_SECRET: not needed — use 'npm run platform:admin' on the box.
DEMO_RESET_SECRET=""
DIRECTORY_SYNC_SECRET=""
PLATFORM_BOOTSTRAP_SECRET=""

# ── Logins for 'npm run db:seed' (demo data) — set BEFORE seeding, or the ──
# ── seed falls back to the published admin@crmitdesk.com / Admin@123.    ──
SEED_ADMIN_EMAIL=""
SEED_CRM_EMAIL=""
SEED_SALES_EMAIL=""
SEED_ITMANAGER_EMAIL=""
SEED_ITAGENT_EMAIL=""
SEED_PASSWORD=""
EOF
  chmod 600 "$ENV_FILE"
  echo "Generated fresh secrets (values not printed)."
fi

# ── systemd: API, release puller, nightly backup ────────────────────────
log "Installing systemd units"
install -m 755 "$APP/deploy/zenkara-pull-deploy.sh" /usr/local/bin/zenkara-pull-deploy.sh
install -m 755 "$APP/deploy/zenkara-crm-backup.sh" /usr/local/bin/zenkara-crm-backup.sh

cat > /etc/systemd/system/zenkara-crm-api.service <<EOF
[Unit]
Description=Zenkara 360 CRM API
After=network-online.target postgresql.service
Wants=network-online.target

[Service]
User=$RUN_USER
WorkingDirectory=$APP/server
EnvironmentFile=$ENV_FILE
ExecStart=/usr/bin/node dist/index.js
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

cat > /etc/systemd/system/zenkara-deploy.service <<EOF
[Unit]
Description=Pull and apply the latest Zenkara release from S3
After=network-online.target

[Service]
Type=oneshot
Environment=ZENKARA_DEPLOY_BUCKET=$DEPLOY_BUCKET
ExecStart=/usr/local/bin/zenkara-pull-deploy.sh
EOF

cat > /etc/systemd/system/zenkara-deploy.timer <<'EOF'
[Unit]
Description=Check for a new Zenkara release every minute

[Timer]
OnBootSec=2min
OnUnitActiveSec=1min
AccuracySec=10s

[Install]
WantedBy=timers.target
EOF

cat > /etc/systemd/system/zenkara-crm-backup.service <<EOF
[Unit]
Description=Back up the Zenkara CRM database

[Service]
Type=oneshot
Environment=BACKUP_S3_BUCKET=$DEPLOY_BUCKET
ExecStart=/usr/local/bin/zenkara-crm-backup.sh
EOF

cat > /etc/systemd/system/zenkara-crm-backup.timer <<'EOF'
[Unit]
Description=Nightly Zenkara CRM database backup

[Timer]
OnCalendar=*-*-* 02:30:00
Persistent=true

[Install]
WantedBy=timers.target
EOF

systemctl daemon-reload
# The API has no build to run until the first release lands; the puller
# starts it (systemctl restart) once one does.
systemctl enable zenkara-crm-api.service
systemctl enable --now zenkara-deploy.timer zenkara-crm-backup.timer

# ── nginx ───────────────────────────────────────────────────────────────
log "Configuring nginx for $DOMAIN"
SITE=/etc/nginx/sites-available/zenkara-crm
if [ -f "$SITE" ] && grep -q "listen 443" "$SITE"; then
  echo "$SITE already has HTTPS (certbot) — leaving it"
else
  sed "s/__DOMAIN__/$DOMAIN/g" "$APP/deploy/nginx-site.conf" > "$SITE"
fi
ln -sf "$SITE" /etc/nginx/sites-enabled/zenkara-crm
rm -f /etc/nginx/sites-enabled/default
mkdir -p "$APP/client/dist"
nginx -t && systemctl reload nginx

log "Done. Next:"
cat <<EOF
  1. Fill in the external keys:  sudo nano $ENV_FILE   (SMTP_PASS, GOOGLE_*, GROQ_API_KEY, ...)
  2. Push to main (or re-run the Deploy workflow) — the first release installs,
     migrates the empty database and starts the API within ~1 minute:
       journalctl -u zenkara-deploy -f
  3. Point DNS for $DOMAIN at this server, then enable HTTPS:
       sudo bash $APP/deploy/enable-https.sh zenkaratech@gmail.com
  4. Create your platform admin login:
       cd $APP/server && sudo npm run platform:admin -- --email <you> --password '<strong>' --name '<name>'
EOF
